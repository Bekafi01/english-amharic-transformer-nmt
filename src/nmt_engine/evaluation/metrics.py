"""Standardized evaluation metrics for Machine Translation: SacreBLEU, chrF++, and TER."""

import sacrebleu


def compute_bleu(
    hypotheses: list[str],
    references: list[str],
    tokenize: str = "intl",
) -> float:
    """Computes corpus-level SacreBLEU score between hypothesis and reference translations.

    Args:
        hypotheses: List of candidate translation strings generated by model.
        references: List of ground-truth reference translation strings.
        tokenize: SacreBLEU tokenization standard ('intl', '13a', 'flores200', etc.).

    Returns:
        BLEU score on a 0-100 scale.
    """
    if not hypotheses or not references:
        return 0.0
    bleu = sacrebleu.corpus_bleu(hypotheses, [references], tokenize=tokenize)
    return float(bleu.score)


def compute_chrf(
    hypotheses: list[str],
    references: list[str],
    word_order: int = 2,
) -> float:
    """Computes chrF++ (character n-gram F-score + word n-grams) (Popovic, 2017).

    Essential metric for morphologically rich Semitic languages like Amharic,
    rewarding sub-word stem and affix matches that BLEU penalizes as full-word mismatches.

    Args:
        hypotheses: List of candidate translation strings.
        references: List of gold reference translation strings.
        word_order: Word n-gram order (word_order=2 corresponds to chrF++).

    Returns:
        chrF++ score on a 0-100 scale.
    """
    if not hypotheses or not references:
        return 0.0
    chrf = sacrebleu.corpus_chrf(hypotheses, [references], word_order=word_order)
    return float(chrf.score)


def compute_ter(
    hypotheses: list[str],
    references: list[str],
    normalized: bool = True,
) -> float:
    """Computes Translation Edit Rate (TER) (Snover et al., 2006).

    Measures the minimum number of human post-edits required to match the reference.
    Lower score is better.

    Args:
        hypotheses: List of candidate translations.
        references: List of gold reference translations.
        normalized: Whether to apply standard shift normalization.

    Returns:
        TER score on a 0-100 scale (lower indicates higher quality).
    """
    if not hypotheses or not references:
        return 0.0
    ter = sacrebleu.corpus_ter(hypotheses, [references], normalized=normalized)
    return float(ter.score)


def compute_all_metrics(
    hypotheses: list[str],
    references: list[str],
) -> dict[str, float]:
    """Computes BLEU, chrF++, and TER simultaneously across candidate translations.

    Args:
        hypotheses: List of candidate translations.
        references: List of gold reference translations.

    Returns:
        Dictionary mapping metric names ('bleu', 'chrf2', 'ter') to floating-point scores.
    """
    return {
        "bleu": compute_bleu(hypotheses, references),
        "chrf2": compute_chrf(hypotheses, references, word_order=2),
        "ter": compute_ter(hypotheses, references),
    }
